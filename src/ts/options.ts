/** 1回の稽古で増える経験値 */
export const XP_PRACTICE = 10;
export const XP_INSIGHT = 5;
export const XP_EPISODE = 5;

export function practiceXp(p: Practice): number {
  let xp = XP_PRACTICE;
  if (p.insight.trim()) xp += XP_INSIGHT;
  if (p.episode) xp += XP_EPISODE;
  return xp;
}

