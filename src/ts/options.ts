/** 稽古の記録を、面接や評価面談で話せる形に整えてもらうためのプロンプト */
export function episodePrompt(p: Practice): string {
  const s = skillOf(p.skill);
  const lines = [
    `私が「${s.name}」というスキルを実践したエピソードです。`,
    '',
  ];
  if (p.drill.trim()) lines.push(`取り組んだこと：${p.drill.trim()}`);
  if (p.scene.trim()) lines.push(`場面：${p.scene.trim()}`);
  lines.push(`やってみた結果：${p.result.trim() || '（未記入）'}`);
  if (p.insight.trim()) lines.push(`気づき：${p.insight.trim()}`);
  lines.push(
    '',
    'これを、面接や評価面談で1分で話せるエピソードに整えてください。',
    '',
    '# 出力形式',
    '- 状況・自分がしたこと・結果・学び の4つに分けて、それぞれ1〜2文',
    '- 事実を盛らず、書いてある内容の範囲で',
    '- 最後に、この経験から言える自分の強みを一言で',
  );
  return lines.join('\n');
}

